create or replace function public.save_player_equipment(p_equipment jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'Autenticação necessária.';
  end if;
  if p_equipment is null or jsonb_typeof(p_equipment) <> 'array' or jsonb_array_length(p_equipment) > 35 then
    raise exception 'Lista de equipamentos inválida.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_equipment) as e(character_id uuid, inventory_item_id uuid, slot text)
    left join public.characters c on c.id = e.character_id and c.user_id = v_user_id
    left join public.inventory i on i.id = e.inventory_item_id and i.user_id = v_user_id
    left join public.item_catalog catalog on catalog.definition_id = i.item_definition_id
    where e.character_id is null or c.id is null
       or e.inventory_item_id is null or i.id is null
       or e.slot is null or catalog.slot is distinct from e.slot
       or (catalog.allowed_classes is not null and not (c.class_id = any(catalog.allowed_classes)))
       or c.level < catalog.min_level
  ) then
    raise exception 'Equipamento inválido, incompatível ou não pertencente ao jogador.';
  end if;

  if exists (
    select 1 from jsonb_to_recordset(p_equipment) as e(character_id uuid, inventory_item_id uuid, slot text)
    group by e.character_id, e.slot having count(*) > 1
  ) or exists (
    select 1 from jsonb_to_recordset(p_equipment) as e(character_id uuid, inventory_item_id uuid, slot text)
    group by e.inventory_item_id having count(*) > 1
  ) then
    raise exception 'Um espaço ou item foi utilizado mais de uma vez.';
  end if;

  delete from public.equipped_items where user_id = v_user_id;

  insert into public.equipped_items (user_id, character_id, inventory_item_id, slot)
  select v_user_id, e.character_id, e.inventory_item_id, e.slot
  from jsonb_to_recordset(p_equipment) as e(character_id uuid, inventory_item_id uuid, slot text);
end;
$$;

revoke all on function public.save_player_equipment(jsonb) from public;
