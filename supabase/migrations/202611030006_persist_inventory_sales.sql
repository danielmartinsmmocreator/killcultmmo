create or replace function public.sell_player_inventory_item(p_inventory_item_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_definition_id text;
  v_sell_price integer;
  v_gold bigint;
begin
  if v_user_id is null then
    raise exception 'Autenticação necessária.';
  end if;
  if p_inventory_item_id is null then
    raise exception 'Item inválido.';
  end if;

  select i.item_definition_id, catalog.sell_price
    into v_definition_id, v_sell_price
  from public.inventory i
  join public.item_catalog catalog on catalog.definition_id = i.item_definition_id
  where i.id = p_inventory_item_id and i.user_id = v_user_id
  for update of i;

  if not found then
    raise exception 'Item não encontrado no inventário.';
  end if;

  if exists (
    select 1 from public.equipped_items e
    where e.inventory_item_id = p_inventory_item_id
      and e.user_id = v_user_id
  ) then
    raise exception 'Remova o equipamento do personagem antes de vendê-lo.';
  end if;

  update public.player_wallet
  set gold = gold + v_sell_price,
      updated_at = now()
  where user_id = v_user_id
  returning gold into v_gold;

  if not found then
    raise exception 'Carteira do jogador não encontrada.';
  end if;

  delete from public.inventory
  where id = p_inventory_item_id and user_id = v_user_id;

  if not found then
    raise exception 'Não foi possível remover o item vendido.';
  end if;

  return jsonb_build_object(
    'item_definition_id', v_definition_id,
    'gold_credited', v_sell_price,
    'wallet_gold', v_gold
  );
end;
$$;

revoke all on function public.sell_player_inventory_item(uuid) from public;
revoke all on function public.sell_player_inventory_item(uuid) from anon;
grant execute on function public.sell_player_inventory_item(uuid) to authenticated;
